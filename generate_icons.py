def make_svg(inner_svg: str, color: str, size: int = 64, stroke_width: float = 2.0) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">'
        f'{inner_svg}'
        f'</svg>'
    )

def generate():
    out_dir = Path("assets") / "icons"
    out_dir.mkdir(parents=True, exist_ok=True)

    colors = {
        "light": "#202020",
        "dark": "#f3f3f3",
        "accent": "#0078d4",
        "blue": "#3b82f6",
        "purple": "#8b5cf6",
        "green": "#10b981",
        "amber": "#f59e0b",
        "white": "#ffffff",
    }

    count = 0
    for name, inner in ICONS_SVG.items():
        # Light & Dark standard variants
        for mode in ("light", "dark", "accent"):
            svg = make_svg(inner, colors[mode], size=64)
            png_bytes = resvg_py.svg_to_bytes(svg)
            (out_dir / f"{name}_{mode}.png").write_bytes(png_bytes)
            count += 1

        # White variant for colored pills/buttons
        svg = make_svg(inner, colors["white"], size=64)
        png_bytes = resvg_py.svg_to_bytes(svg)
        (out_dir / f"{name}_white.png").write_bytes(png_bytes)
        count += 1

    # Special colored icons for categories
    for name, color_key in [("music", "blue"), ("film", "purple"), ("image", "green"), ("wrench", "amber")]:
        svg = make_svg(ICONS_SVG[name], colors[color_key], size=64)
        png_bytes = resvg_py.svg_to_bytes(svg)
        (out_dir / f"{name}_color.png").write_bytes(png_bytes)
        count += 1

    print(f"Generated {count} icons in {out_dir.resolve()} successfully!")

if __name__ == "__main__":
    generate()
